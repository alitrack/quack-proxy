package config

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// PRD §4.2 (2026-11-13 revision): "token 不得明文落盘；status --json 默认不
// 输出；确需持久化时 0600 + 显式开关". The switch defaults OFF, and when it
// is off an omitted token is unrecoverable (status.json is the daemon's only
// out-of-process channel), so Load must fail loud rather than start a shard
// nobody can authenticate to. These tests pin that decision at config time.

func writeR14Config(t *testing.T, yaml string) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), "config.yaml")
	if err := os.WriteFile(p, []byte(yaml), 0600); err != nil {
		t.Fatal(err)
	}
	return p
}

func r14DB(t *testing.T) string {
	t.Helper()
	return filepath.Join(t.TempDir(), "shard.db")
}

func TestPersistTokensDefaultsOff(t *testing.T) {
	db := r14DB(t)
	cfg, err := Load(writeR14Config(t, `
global:
  log_level: info
shards:
  - name: s1
    database: `+db+`
    token: operator-supplied-secret
`))
	if err != nil {
		t.Fatalf("Load with an explicit token must succeed by default: %v", err)
	}
	if cfg.Global.PersistTokens {
		t.Fatal("global.persist_tokens defaulted to true; PRD §4.2 requires cleartext tokens OFF disk by default")
	}
}

func TestDefaultRefusesAutoGeneratedToken(t *testing.T) {
	db := r14DB(t)
	_, err := Load(writeR14Config(t, `
shards:
  - name: analytics
    database: `+db+`
`))
	if err == nil {
		t.Fatal("Load accepted a config with no token and no persist_tokens switch; the generated credential would be unrecoverable")
	}
	for _, want := range []string{"analytics", "persist_tokens", "explicit token"} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("error %q must mention %q so an operator can fix it", err, want)
		}
	}
}

func TestExplicitFalseAlsoRefusesAutoGeneratedToken(t *testing.T) {
	db := r14DB(t)
	_, err := Load(writeR14Config(t, `
global:
  persist_tokens: false
shards:
  - name: s1
    database: `+db+`
`))
	if err == nil || !strings.Contains(err.Error(), "persist_tokens") {
		t.Fatalf("explicit persist_tokens: false must behave like the default, got %v", err)
	}
}

func TestExplicitSwitchAllowsAutoGeneratedToken(t *testing.T) {
	db := r14DB(t)
	cfg, err := Load(writeR14Config(t, `
global:
  persist_tokens: true
shards:
  - name: s1
    database: `+db+`
`))
	if err != nil {
		t.Fatalf("explicit opt-in must restore the legacy auto-token path: %v", err)
	}
	if !cfg.Global.PersistTokens {
		t.Fatal("persist_tokens: true was not parsed")
	}
	if cfg.Shards[0].Token != "" {
		t.Fatalf("token must still be generated at start, not at load: %q", cfg.Shards[0].Token)
	}
}

func TestSwitchDoesNotWeakenOtherValidation(t *testing.T) {
	db := r14DB(t)
	// A quote in an explicit token is still a shell/SQL injection even when
	// persistence is explicitly enabled.
	_, err := Load(writeR14Config(t, `
global:
  persist_tokens: true
shards:
  - name: s1
    database: `+db+`
    token: "it's"
`))
	if err == nil || !strings.Contains(err.Error(), "single quote") {
		t.Fatalf("the opt-in must not bypass token quoting validation, got %v", err)
	}
}
