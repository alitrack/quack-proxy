// Package proxy generates HAProxy configuration for the Quack cluster.
package proxy

import (
	"fmt"
	"os"
	"strings"
	"time"

	"github.com/alitrack/quack-proxy/internal/config"
)

// connectAddr maps a (possibly bind-only) address to one a proxy can connect
// to. 0.0.0.0 binds all interfaces but is not dialable, so it becomes the
// loopback; any explicit host is used as-is (a LAN address is the intended
// value when shards live on another machine).
func connectAddr(bindHost string) string {
	if bindHost == "" || bindHost == "0.0.0.0" || bindHost == "::" {
		return "127.0.0.1"
	}
	return bindHost
}

// singleBackendOnly reports whether one HAProxy backend can safely front the
// configured shards. On a single host the answer is only ever "yes" for ONE
// shard (a pure port-forward, no balancing semantics):
//
//   - different .db files are PARTITIONS, not replicas: round-robin across
//     them returns non-deterministic results and one VIP token cannot
//     authenticate against independently generated per-shard tokens;
//   - the SAME .db file cannot be opened by two DuckDB writers — verified on
//     v2.0.0: "IO Error: Could not set lock on file ... Conflicting lock is
//     held". Two shard processes would not even start.
//
// Real replicas require cross-machine replication, which is out of scope
// (docs/SCOPE.md §3). See R-04.
func singleBackendOnly(shards []config.ShardConfig) bool {
	return len(shards) == 1
}

// GenerateHAProxy writes an HAProxy configuration file from the configured
// shards. It is a pure function of the config so the standalone `gen-proxy`
// command works with no daemon running: every configured shard becomes a
// `server` line, and HAProxy's active `check inter 5s` excludes any that is
// down at runtime.
func GenerateHAProxy(cfg *config.Config, outputPath string) error {
	if cfg.Proxy == nil || !cfg.Proxy.Enabled {
		return fmt.Errorf("proxy generation is not enabled in config")
	}
	if len(cfg.Shards) == 0 {
		return fmt.Errorf("no shards configured")
	}
	if cfg.Proxy.BindPort <= 0 || cfg.Proxy.BindPort > 65535 {
		return fmt.Errorf("proxy.bind_port is required and must be a valid port")
	}
	if !singleBackendOnly(cfg.Shards) {
		return fmt.Errorf("refusing to load-balance %d shards on one host: different .db files are partitions (non-deterministic round-robin, distinct tokens), and the same .db cannot be opened by two DuckDB writers (file-lock conflict). Use per-shard ATTACH statements; real replicas require cross-machine replication, which is out of scope (see docs/SCOPE.md)", len(cfg.Shards))
	}

	addr := connectAddr(cfg.Listener.BindHost)

	var sb strings.Builder
	sb.WriteString("# Generated by quack-proxy — DO NOT EDIT\n")
	sb.WriteString("# One backend, one shard: a single-host port-forward, NOT a replica\n")
	sb.WriteString("# group. Multi-shard backends are rejected (R-04); see docs/SCOPE.md.\n")
	sb.WriteString(fmt.Sprintf("# Generated at: %s\n", time.Now().Format(time.RFC3339)))
	// R-23: a real `haproxy -c -f` check plus a live forwarding test passed
	// (scripts/verify-deploy.sh), but HAProxy >= 3.x warns at STARTUP that
	// this config runs as root with no chroot/user. quack-proxy only WRITES
	// the file — it never starts HAProxy — and cannot provision a host-local
	// account or chroot directory, so we do not inject them BY DEFAULT
	// (doing so would make the generated config unusable on hosts that lack
	// them). Spell out the required hardening instead of hiding the warning.
	// proxy.hardened: true is the OPT-IN that emits them for hosts prepared
	// by scripts/verify-hardening.sh. See SECURITY.md.
	sb.WriteString("#\n")
	if cfg.Proxy.Hardened {
		sb.WriteString("# SECURITY (R-23): HARDENING ENABLED. chroot/user/group in the\n")
		sb.WriteString("# global section below are ACTIVE; HAProxy drops root on startup.\n")
		sb.WriteString("# The host MUST have the haproxy account and a root-owned 0755\n")
		sb.WriteString("# /var/lib/haproxy directory (scripts/verify-hardening.sh provisions\n")
		sb.WriteString("# and verifies them). Without them HAProxy refuses to start.\n")
	} else {
		sb.WriteString("# SECURITY (R-23): this config starts as root with no chroot/user.\n")
		sb.WriteString("# HAProxy >= 3.x warns about that at runtime. Before production use,\n")
		sb.WriteString("# add to the global section (and pre-provision them on the host):\n")
		sb.WriteString("#     chroot /var/lib/haproxy\n")
		sb.WriteString("#     user haproxy\n")
		sb.WriteString("#     group haproxy\n")
		sb.WriteString("# Or set proxy.hardened: true after running\n")
		sb.WriteString("# scripts/verify-hardening.sh to have them emitted for you.\n")
	}
	sb.WriteString("# Prefer a service manager over the 'daemon' directive below.\n")
	sb.WriteString("# See docs/SECURITY.md.\n#\n\n")
	sb.WriteString("global\n")
	sb.WriteString("    log /dev/log local0\n")
	sb.WriteString("    maxconn 4096\n")
	if cfg.Proxy.Hardened {
		sb.WriteString("    chroot /var/lib/haproxy\n")
		sb.WriteString("    user haproxy\n")
		sb.WriteString("    group haproxy\n")
	}
	sb.WriteString("    daemon\n\n")
	sb.WriteString("defaults\n")
	sb.WriteString("    mode tcp\n")
	sb.WriteString("    timeout connect 5s\n")
	sb.WriteString("    timeout client 30s\n")
	sb.WriteString("    timeout server 30s\n\n")
	sb.WriteString("frontend quack_frontend\n")
	sb.WriteString(fmt.Sprintf("    bind *:%d\n", cfg.Proxy.BindPort))
	sb.WriteString("    default_backend quack_backend\n\n")
	sb.WriteString("backend quack_backend\n")
	if cfg.Proxy.Mode == "leastconn" {
		sb.WriteString("    balance leastconn\n")
	} else {
		sb.WriteString("    balance roundrobin\n")
	}

	for _, s := range cfg.Shards {
		sb.WriteString(fmt.Sprintf("    server %s %s:%d check inter 5s\n",
			s.Name, addr, s.Port))
	}

	return os.WriteFile(outputPath, []byte(sb.String()), 0644)
}
