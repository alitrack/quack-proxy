// Package proxy generates HAProxy configuration for the Quack cluster.
package proxy

import (
	"fmt"
	"os"
	"strings"
	"time"

	"github.com/alitrack/quack-proxy/internal/config"
)

// connectAddr maps a (possibly bind-only) address to one a proxy can connect
// to. 0.0.0.0 binds all interfaces but is not dialable, so it becomes the
// loopback; any explicit host is used as-is (a LAN address is the intended
// value when shards live on another machine).
func connectAddr(bindHost string) string {
	if bindHost == "" || bindHost == "0.0.0.0" || bindHost == "::" {
		return "127.0.0.1"
	}
	return bindHost
}

// GenerateHAProxy writes an HAProxy configuration file from the configured
// shards. It is a pure function of the config so the standalone `gen-proxy`
// command works with no daemon running: every configured shard becomes a
// `server` line, and HAProxy's active `check inter 5s` excludes any that is
// down at runtime.
func GenerateHAProxy(cfg *config.Config, outputPath string) error {
	if cfg.Proxy == nil || !cfg.Proxy.Enabled {
		return fmt.Errorf("proxy generation is not enabled in config")
	}
	if len(cfg.Shards) == 0 {
		return fmt.Errorf("no shards configured")
	}
	if cfg.Proxy.BindPort <= 0 || cfg.Proxy.BindPort > 65535 {
		return fmt.Errorf("proxy.bind_port is required and must be a valid port")
	}

	addr := connectAddr(cfg.Listener.BindHost)

	var sb strings.Builder
	sb.WriteString("# Generated by quack-proxy — DO NOT EDIT\n")
	sb.WriteString(fmt.Sprintf("# Generated at: %s\n\n", time.Now().Format(time.RFC3339)))
	sb.WriteString("global\n")
	sb.WriteString("    log /dev/log local0\n")
	sb.WriteString("    maxconn 4096\n")
	sb.WriteString("    daemon\n\n")
	sb.WriteString("defaults\n")
	sb.WriteString("    mode tcp\n")
	sb.WriteString("    timeout connect 5s\n")
	sb.WriteString("    timeout client 30s\n")
	sb.WriteString("    timeout server 30s\n\n")
	sb.WriteString("frontend quack_frontend\n")
	sb.WriteString(fmt.Sprintf("    bind *:%d\n", cfg.Proxy.BindPort))
	sb.WriteString("    default_backend quack_backend\n\n")
	sb.WriteString("backend quack_backend\n")
	if cfg.Proxy.Mode == "leastconn" {
		sb.WriteString("    balance leastconn\n")
	} else {
		sb.WriteString("    balance roundrobin\n")
	}

	for _, s := range cfg.Shards {
		sb.WriteString(fmt.Sprintf("    server %s %s:%d check inter 5s\n",
			s.Name, addr, s.Port))
	}

	return os.WriteFile(outputPath, []byte(sb.String()), 0644)
}
