func baseProxyCfg() *config.Config {
	return &config.Config{
		Global:   config.GlobalConfig{DuckDBBin: "duckdb"},
		Listener: config.ListenerConfig{BindHost: "0.0.0.0", PortStart: 9491},
		Shards: []config.ShardConfig{
			{Name: "shard1", Database: "/tmp/a.db", Port: 9491},
			{Name: "shard2", Database: "/tmp/l.db", Port: 9492},
		},
		Proxy: &config.ProxyConfig{
			Enabled:  true,
			BindPort: 9490,
			Mode:     "roundrobin",
		},
	}
}

func TestGenerateHAProxyRejectsCrossDatabaseShards(t *testing.T) {
	tmp := t.TempDir()
	cfg := baseProxyCfg() // two shards, different .db files, no shared token
	out := filepath.Join(tmp, "haproxy.cfg")

	// Shards are partitions, not replicas: round-robin across them makes
	// queries non-deterministic and one VIP token cannot authenticate
	// against independently generated tokens (R-04).
	err := GenerateHAProxy(cfg, out)
	if err == nil {
		t.Fatal("shards with different databases must not be put behind one LB")
	}
	if !strings.Contains(err.Error(), "refusing to load-balance") {
		t.Errorf("unexpected error: %v", err)
	}
	if _, statErr := os.Stat(out); !os.IsNotExist(statErr) {
		t.Error("no HAProxy config should be written for an unsafe topology")
	}
}

func TestGenerateHAProxyLeastConn(t *testing.T) {
	tmp := t.TempDir()
	cfg := baseProxyCfg()
	cfg.Proxy.Mode = "leastconn"
	cfg.Listener.BindHost = "192.168.1.10" // an explicit LAN host must pass through
	// Only a single shard may be fronted by one backend (R-04).
	cfg.Shards = cfg.Shards[:1]

	outputPath := filepath.Join(tmp, "haproxy.cfg")
	if err := GenerateHAProxy(cfg, outputPath); err != nil {
		t.Fatalf("GenerateHAProxy(): %v", err)
	}

	data, _ := os.ReadFile(outputPath)
	content := string(data)
	if !strings.Contains(content, "balance leastconn") {
		t.Error("expected leastconn balance mode")
	}
	if !strings.Contains(content, "server shard1 192.168.1.10:9491") {
		t.Errorf("expected LAN address preserved in server line, got:\n%s", content)
	}
}

