#!/usr/bin/env bash
# LAN cleartext audit + PRD §4.2 deployment acceptance for quack-proxy (R-05).
#
# This job has TWO halves, and they must never be conflated:
#
# 1. AUDIT (unchanged since r8): with a real AF_PACKET capture, prove that a
#    shard exposed on a LAN interface (listener.bind_host: 0.0.0.0) carries
#    its token, Bearer header and SQL body in cleartext, because quack-proxy
#    hardcodes disable_ssl=true. Since r14 it ALSO asserts the separate PRD
#    §4.2 fix: the same token must NOT be written to status.json by default.
#    A TLS control channel on the same L2 segment carries a second canary
#    that must NOT appear in the capture - that negative control proves the
#    sniffer really parses wire payloads and is not just a grep over a log.
#    A third check uses the real CLI to confirm proxy.ssl.enabled=true is
#    rejected at config load ("not implemented").
#
# 2. ACCEPTANCE (added in r15): execute the mitigation the PRD ALREADY
#    specifies rather than waiting for a new product decision. PRD §4.2
#    (v0.1 original, "Nginx 反向代理做 SSL termination + 固定 token"),
#    SCOPE §3 ("内建 TLS 终止" is a non-goal, terminate in an external proxy)
#    and SECURITY.md's operator checklist all say: the product does NOT
#    provide TLS; keep the shard on loopback and terminate TLS in an external
#    reverse proxy. This script now stands up a SECOND real daemon bound to
#    127.0.0.1 plus a real HAProxy TLS-terminating frontend, sends the same
#    class of credential-bearing request through HTTPS to the real shard,
#    and asserts on the wire that:
#      * the client gets 200 + the shard's own greeting (i.e. real forwarding,
#        not a stub answering on behalf of the proxy);
#      * no credential / Bearer / SQL canary is readable on the LAN;
#      * the captured bytes on that port are TLS handshake records;
#      * NO payload at all appears on the loopback backend port (it never
#        crosses eth0);
#      * a LAN client CANNOT connect to the loopback-bound shard directly.
#    This is an ACCEPTANCE of the existing deployment decision, NOT a product
#    TLS feature: supervisor.go still emits disable_ssl=true, proxy.ssl is
#    still dead config, and gen-proxy still emits no TLS frontend. The HAProxy
#    config here is operator-supplied, generated by this drill, not by the
#    product. Do not read a passing gate as "quack-proxy now has TLS".
#
# Topology (all local, images are already used by other required gates):
#   * one Docker user-defined bridge = a stand-in for a shared LAN segment;
#   * server container: the REAL quack-proxy daemon starts shard A on
#     0.0.0.0 (bad deployment, control) and shard B on 127.0.0.1 (correct
#     deployment), both backed by scripts/drill-stub.go, plus a TLS control
#     server. Runtime state lives in the container's own /tmp, not on the
#     bind mount, so 0600 checks are meaningful.
#   * HAProxy container: --network container:<server> so its plain backend
#     leg to 127.0.0.1:LOOPBACK_PORT stays inside the host netns, while its
#     TLS frontend is reachable from the bridge.
#   * sniffer container: a SEPARATE container attached with
#     --network container:<server>, i.e. an on-path observer on that segment.
#     It never reads the server's memory or logs - only raw Ethernet frames.
#   * client container: another container on the same bridge. It reaches the
#     server by its bridge IP/name, so traffic really crosses the segment.
#
# Scope limits (do not overstate): the shard endpoint is the drill stub, not
# the real DuckDB/Quack engine (covered by scripts/quack-e2e.sh). The TLS
# terminator is a real vendor HAProxy binary with a self-signed throwaway
# cert, not a production-grade Nginx/CA setup. This proves the TRANSPORT
# property and the deployment topology; it does not exercise the Quack
# protocol, certificate lifecycle or fingerprint rotation.
#
# When TLS termination is actually added to the product, gate 1 will
# (correctly) start failing: update the assertions and docs together instead
# of deleting it. Gate 2 stays valid either way (an external proxy can still
# sit in front of a TLS shard).
#
# Usage:
#   bash scripts/verify-plaintext.sh                      # builds with go
#   bash scripts/verify-plaintext.sh --proxy-bin /tmp/quack-proxy \
#                                    --stub-bin  /tmp/drill-stub
#   bash scripts/verify-plaintext.sh --image python:3.12-slim --work /tmp/pt
# Negative control (must FAIL at the canary assertion, with no PASS marker):
#   PLAINTEXT_INJECT_CLEARTEXT=1 bash scripts/verify-plaintext.sh ...
#
# Supply chain (r17): the DEFAULT images are pinned by manifest digest, not by
# a floating tag - the same standard this repo already applies to every
# `uses:` action. `internal/cicontract.CheckImagePins` enforces it. An explicit
# --image / PLAINTEXT_IMAGE / PLAINTEXT_HAPROXY_IMAGE override may still use a
# tag for local/offline runs; that is an operator choice, not what CI runs.
# Digests must be rotated deliberately when upgrading the base images.
#
# Requirements: docker, openssl (host), python3 inside the image. If the two
# binaries are not supplied, `go` is needed to build them (CGO_ENABLED=0).
#
# Exit: 0 = every assertion held, non-zero = first failed assertion.
set -euo pipefail
# Git Bash rewrites container-internal /work paths to host paths. The -v
# argument is already a Windows path from cygpath, so disabling MSYS path
# conversion is safe for it while keeping every /work literal intact.
export MSYS_NO_PATHCONV=1

HTTP_PORT="${PLAINTEXT_HTTP_PORT:-19741}"
TLS_PORT="${PLAINTEXT_TLS_PORT:-19742}"
LOOPBACK_PORT="${PLAINTEXT_LOOPBACK_PORT:-19745}"
TLS_TERM_PORT="${PLAINTEXT_TLS_TERM_PORT:-19746}"
TOKEN="qp-lan-cleartext-token"
TLS_TOKEN="qp-tls-control-token"
LOOP_TOKEN="qp-external-tls-token"
LOOP_GREETING="external-tls-backend-ok"
# Both images are already used by other required CI gates; no new dependency
# class is introduced. Digest-pinned since r17 (CheckImagePins enforces it);
# override with env vars / --image for local or offline runs.
IMAGE="${PLAINTEXT_IMAGE:-python@sha256:0b2cfd528ad7c43ba83de95e2788393cf545aae1ed738868e961454bd38a760a}"
HAPROXY_IMAGE="${PLAINTEXT_HAPROXY_IMAGE:-haproxy@sha256:fce63f5dde742cd1f2b883ab39f7d4f9f88788827dd54fcfa864f63b9eec3bc8}"
# NEGATIVE-CONTROL switch: PLAINTEXT_INJECT_CLEARTEXT=1 makes the client also
# put one cleartext credential-bearing request on the LAN port. The gate MUST
# then fail at the canary assertion and must NOT print PLAINTEXT_AUDIT_PASSED.
INJECT="${PLAINTEXT_INJECT_CLEARTEXT:-0}"
PROXY_BIN=""
STUB_BIN=""
WORK=""

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

usage() {
  sed -n '2,68p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
  exit "${1:-0}"
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --proxy-bin) PROXY_BIN="$2"; shift 2 ;;
    --stub-bin)  STUB_BIN="$2"; shift 2 ;;
    --image)     IMAGE="$2"; shift 2 ;;
    --work)      WORK="$2"; shift 2 ;;
    -h|--help)   usage 0 ;;
    *) echo "unknown argument: $1" >&2; usage 1 ;;
  esac
done

fail() { echo "FAIL: $*" >&2; exit 1; }
log()  { echo "==> $*"; }

CLEAN_WORK=0
if [[ -z "$WORK" ]]; then WORK="$(mktemp -d)"; CLEAN_WORK=1; else mkdir -p "$WORK"; fi
# The official haproxy image runs as the unprivileged `haproxy` user, so a
# 0700 mktemp directory bind-mounted into it is unreadable ("Cannot open
# configuration file ... Permission denied"). Make the directory traversable
# and keep generated files world-readable; the config carries no secrets.
chmod 755 "$WORK"
# Git Bash needs a Windows-style path for -v; Linux CI uses the path as-is.
if command -v cygpath >/dev/null 2>&1; then
  VOL="$(cygpath -w "$WORK" | tr '\\' '/')"
else
  VOL="$WORK"
fi

TAG="qp-plain-$$"
NET="${TAG}-net"
SRV="${TAG}-srv"
SNIFF="${TAG}-sniff"
HAP="${TAG}-hap"

cleanup() {
  local rc=$?
  set +e
  docker rm -f "$SNIFF" "$HAP" "$SRV" >/dev/null 2>&1
  docker network rm "$NET" >/dev/null 2>&1
  # `find -depth -delete` also works on Git Bash, where a sandbox hook may
  # reject `rm -rf` on MSYS /tmp paths and leave the work dir behind.
  if [[ "$CLEAN_WORK" -eq 1 ]]; then find "$WORK" -depth -delete >/dev/null 2>&1 || true; fi
  return "$rc"
}
trap cleanup EXIT

# ---- preflight --------------------------------------------------------------
command -v docker >/dev/null 2>&1 || fail "docker is required"
docker info >/dev/null 2>&1 || fail "docker daemon is not reachable"
command -v openssl >/dev/null 2>&1 || fail "openssl is required to mint the TLS certs"
for img in "$IMAGE" "$HAPROXY_IMAGE"; do
  if ! docker image inspect "$img" >/dev/null 2>&1; then
    log "pulling ${img} (3 attempts)"
    pulled=0
    for _ in 1 2 3; do
      if docker pull "$img" >/dev/null 2>&1; then pulled=1; break; fi
      sleep 2
    done
    [[ "$pulled" -eq 1 ]] || \
      fail "cannot pull ${img}; point the image env var at a locally cached one"
  fi
done

if [[ -z "$PROXY_BIN" || -z "$STUB_BIN" ]]; then
  command -v go >/dev/null 2>&1 || fail "go not found; pass --proxy-bin and --stub-bin"
  [[ -z "$PROXY_BIN" ]] && PROXY_BIN="$WORK/quack-proxy"
  [[ -z "$STUB_BIN" ]] && STUB_BIN="$WORK/drill-stub"
  (cd "$REPO_ROOT" && CGO_ENABLED=0 go build -o "$PROXY_BIN" ./cmd/quack-proxy) || fail "go build quack-proxy"
  (cd "$REPO_ROOT" && CGO_ENABLED=0 go build -o "$STUB_BIN" ./scripts/drill-stub.go) || fail "go build drill-stub"
fi
# Only check existence here: on a Windows bind mount Git Bash cannot see the
# execute bit even though Docker exposes the file as 0755 inside the container.
[[ -f "$PROXY_BIN" ]] || fail "proxy binary not found: $PROXY_BIN"
[[ -f "$STUB_BIN" ]] || fail "stub binary not found: $STUB_BIN"
cp "$PROXY_BIN" "$WORK/quack-proxy"
cp "$STUB_BIN" "$WORK/drill-stub"
chmod +x "$WORK/quack-proxy" "$WORK/drill-stub"

openssl req -x509 -newkey rsa:2048 -nodes \
  -keyout "$WORK/key.pem" -out "$WORK/cert.pem" -days 1 \
  -subj "/CN=qp-plaintext-audit" >/dev/null 2>&1 || fail "openssl cert generation"
# HAProxy wants cert + key in one PEM. Throwaway self-signed material for a
# local drill only; production certificate lifecycle is deliberately out of
# scope here and remains an operator responsibility.
cat "$WORK/cert.pem" "$WORK/key.pem" > "$WORK/haproxy.pem"
chmod 644 "$WORK/haproxy.pem"

# ---- helpers (written into the shared work dir) -----------------------------
cat > "$WORK/sniff.py" <<'PY'
import os, socket, struct, sys

outdir, portlist, stop = sys.argv[1], sys.argv[2], sys.argv[3]
ports = {int(x) for x in portlist.split(",")}
s = socket.socket(socket.AF_PACKET, socket.SOCK_RAW, socket.htons(0x0003))
s.bind(("eth0", 0))
s.settimeout(0.3)
files, counts = {}, {}
while not os.path.exists(stop):
    try:
        pkt = s.recv(65535)
    except socket.timeout:
        continue
    except OSError as e:
        print("SNIFF_ERR", e, flush=True)
        break
    if len(pkt) < 34 or struct.unpack("!H", pkt[12:14])[0] != 0x0800:
        continue                                  # IPv4 only
    ihl = (pkt[14] & 0x0F) * 4
    if len(pkt) < 14 + ihl + 20 or pkt[14 + 9] != 6:
        continue                                  # TCP only
    total = struct.unpack("!H", pkt[16:18])[0]
    tcp = 14 + ihl
    sp, dp = struct.unpack("!HH", pkt[tcp:tcp + 4])
    off = (pkt[tcp + 12] >> 4) * 4
    payload = pkt[tcp + off:14 + total]
    if not payload:
        continue
    for p in (sp, dp):
        if p not in ports:
            continue
        if p not in files:
            files[p] = open(os.path.join(outdir, "port-%d.bin" % p), "ab", buffering=0)
        files[p].write(payload)
        counts[p] = counts.get(p, 0) + len(payload)
for f in files.values():
    f.close()
with open(os.path.join(outdir, "capture.summary"), "w") as out:
    for p in sorted(ports):
        out.write("%d %d\n" % (p, counts.get(p, 0)))
print("SNIFF_DONE", counts, flush=True)
PY

cat > "$WORK/tls_srv.py" <<'PY'
import http.server, ssl, sys

port, cert, key = int(sys.argv[1]), sys.argv[2], sys.argv[3]


class H(http.server.BaseHTTPRequestHandler):
    def _reply(self):
        n = int(self.headers.get("Content-Length", "0"))
        if n:
            self.rfile.read(n)
        self.send_response(200)
        self.end_headers()
        self.wfile.write(b"tls-control-ok")

    do_GET = _reply
    do_POST = _reply

    def log_message(self, *a):
        pass


http.server.ThreadingHTTPServer.allow_reuse_address = True
srv = http.server.ThreadingHTTPServer(("0.0.0.0", port), H)
ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
ctx.load_cert_chain(cert, key)
srv.socket = ctx.wrap_socket(srv.socket, server_side=True)
srv.serve_forever()
PY

cat > "$WORK/client.py" <<'PY'
import http.client, ssl, sys

(host, hp, tp, tok, tls_tok, term_port, loop_port, loop_tok, greeting, inject) = sys.argv[1:11]
hp, tp, term_port, loop_port = int(hp), int(tp), int(term_port), int(loop_port)


def send(conn, tok, marker):
    body = ("SELECT * FROM secrets WHERE token='%s' AND case='%s';" % (tok, marker)).encode()
    conn.request("POST", "/", body=body, headers={
        "Authorization": "Bearer " + tok,
        "Content-Type": "text/plain",
        "Content-Length": str(len(body)),
    })
    r = conn.getresponse()
    return r.status, r.read()


print("HTTP_ENDPOINT", send(http.client.HTTPConnection(host, hp, timeout=5), tok, "cleartext"))
ctx = ssl._create_unverified_context()
print("TLS_CONTROL", send(http.client.HTTPSConnection(host, tp, context=ctx, timeout=5), tls_tok, "control"))
print("EXTERNAL_TLS_ENDPOINT",
      send(http.client.HTTPSConnection(host, term_port, context=ctx, timeout=5),
           loop_tok, "external-tls"))
try:
    c = http.client.HTTPConnection(host, loop_port, timeout=3)
    c.request("GET", "/")
    c.getresponse().read()
    print("LOOPBACK_DIRECT", "REACHABLE")
except (OSError, http.client.HTTPException) as e:
    print("LOOPBACK_DIRECT", "BLOCKED", type(e).__name__)

if inject == "1":
    # NEGATIVE CONTROL ONLY: deliberately put a cleartext credential-bearing
    # request on the same LAN port. The TLS proxy will reject it, but the
    # Ethernet frame has already crossed the sniffed segment. This proves
    # capture_check.py's "no readable canary" assertion is not a no-op.
    try:
        c = http.client.HTTPConnection(host, term_port, timeout=3)
        c.request("POST", "/", body=b"SELECT * FROM secrets WHERE token='qp-external-tls-token' AND case='external-tls';",
                  headers={"Authorization": "Bearer qp-external-tls-token"})
        c.getresponse().read()
    except (OSError, http.client.HTTPException):
        pass
    print("CLEARTEXT_INJECTED", "1")
