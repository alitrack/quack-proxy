cat > "$WORK/capture_check.py" <<'PY'
import os, sys

outdir, term_port, loop_port = sys.argv[1], int(sys.argv[2]), int(sys.argv[3])


def read(port):
    path = os.path.join(outdir, "port-%d.bin" % port)
    return open(path, "rb").read() if os.path.exists(path) else b""


def has_tls_handshake(data):
    # TLS record: type(0x16) | version(0x03, minor) | length(2) | handshake
    # type(0x01 ClientHello / 0x02 ServerHello) ...
    for i in range(len(data) - 6):
        if data[i] == 0x16 and data[i + 1] == 0x03 and data[i + 2] <= 0x04 \
                and data[i + 5] in (0x01, 0x02):
            return True
    return False


term = read(term_port)
if len(term) < 20:
    sys.exit("FAIL: no payload captured on the TLS-termination port %d" % term_port)
if not has_tls_handshake(term):
    sys.exit("FAIL: captured bytes on the TLS port are not TLS handshake records")
for canary in (b"qp-external-tls-token", b"Authorization: Bearer",
               b"external-tls", b"SELECT * FROM secrets", b"HTTP/1.1 200"):
    if canary in term:
        sys.exit("FAIL: cleartext canary %r visible on the LAN through the TLS proxy" % canary)
loop = read(loop_port)
if loop:
    sys.exit("FAIL: loopback backend traffic appeared on the LAN interface")
print("CAPTURE_OK")
PY

