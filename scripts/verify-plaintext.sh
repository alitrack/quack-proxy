# ---- topology ---------------------------------------------------------------
log "creating isolated bridge ${NET} (${IMAGE} + ${HAPROXY_IMAGE})"
docker network create "$NET" >/dev/null || fail "docker network create"
docker run -d --name "$SRV" --network "$NET" --cap-add=NET_RAW \
  -e DRILL_STUB_BIND=0.0.0.0 -v "$VOL:/work" \
  --entrypoint sleep "$IMAGE" infinity >/dev/null || fail "start server container"
docker exec "$SRV" mkdir -p /tmp/qp-plain /tmp/qp-loop || fail "create runtime dirs"

log "starting real quack-proxy daemon A (bad deployment: 0.0.0.0:${HTTP_PORT})"
docker exec -d "$SRV" sh -c \
  '/work/quack-proxy start -c /work/config.yaml > /work/daemon.log 2>&1' \
  || fail "start daemon A"
docker exec -d "$SRV" python3 /work/tls_srv.py "$TLS_PORT" /work/cert.pem /work/key.pem \
  || fail "start TLS control server"

log "starting real quack-proxy daemon B (PRD deployment: 127.0.0.1:${LOOPBACK_PORT})"
# docker exec -e overrides the container-wide DRILL_STUB_BIND=0.0.0.0 for this
# daemon and its children, so the shard really is loopback-only.
docker exec -d -e DRILL_STUB_BIND=127.0.0.1 -e DRILL_STUB_GREETING="$LOOP_GREETING" \
  "$SRV" sh -c \
  '/work/quack-proxy start -c /work/config-loopback.yaml > /work/daemon-loop.log 2>&1' \
  || fail "start daemon B"

ready=0
for _ in $(seq 1 80); do
  if docker exec "$SRV" python3 -c \
      "import urllib.request; urllib.request.urlopen('http://127.0.0.1:${HTTP_PORT}/', timeout=1).read()" \
      >/dev/null 2>&1; then ready=1; break; fi
  sleep 0.25
done
if [[ "$ready" -ne 1 ]]; then
  echo "--- daemon.log ---" >&2
  docker exec "$SRV" cat /work/daemon.log >&2 || true
  fail "shard A never became reachable"
fi
log "shard A reachable; status.json present: $(docker exec "$SRV" test -f /tmp/qp-plain/status.json && echo yes || echo no)"

loop_ready=0
for _ in $(seq 1 80); do
  if docker exec "$SRV" python3 -c \
      "import urllib.request; assert b'${LOOP_GREETING}' in urllib.request.urlopen('http://127.0.0.1:${LOOPBACK_PORT}/', timeout=1).read()" \
      >/dev/null 2>&1; then loop_ready=1; break; fi
  sleep 0.25
done
if [[ "$loop_ready" -ne 1 ]]; then
  echo "--- daemon-loop.log ---" >&2
  docker exec "$SRV" cat /work/daemon-loop.log >&2 || true
  fail "loopback shard B never became reachable with its own greeting"
fi
log "loopback shard B reachable with greeting ${LOOP_GREETING}"

# Negative control for the vendor parser: a malformed operator config must be
# rejected, otherwise haproxy -c passing below proves nothing.
# `--user root` for the two validation calls only: config parsing needs no
# privilege drop, and it keeps this control independent of the image's default
# user. The running terminator below keeps the image's own user.
chmod 644 "$WORK"/haproxy*.cfg 2>/dev/null || true
docker run --rm --user root --network "container:$SRV" -v "$VOL:/work:ro" \
  --entrypoint haproxy "$HAPROXY_IMAGE" -c -f /work/haproxy-bad.cfg \
  > "$WORK/haproxy-bad.log" 2>&1 || true
if grep -qiE "permission denied|cannot open" "$WORK/haproxy-bad.log"; then
  cat "$WORK/haproxy-bad.log" >&2
  fail "haproxy could not read the mounted config; the negative control is void"
fi
grep -qiE "unknown|error|parsing|unable" "$WORK/haproxy-bad.log" \
  || { cat "$WORK/haproxy-bad.log" >&2
       fail "HAProxy accepted a malformed config; negative control is broken"; }
echo "HAPROXY_BAD_CONFIG_REJECTED=1 (vendor parser really checks the operator config)"

docker run --rm --user root --network "container:$SRV" -v "$VOL:/work:ro" \
  --entrypoint haproxy "$HAPROXY_IMAGE" -c -f /work/haproxy.cfg \
  > "$WORK/haproxy-check.log" 2>&1 \
  || { cat "$WORK/haproxy-check.log" >&2; fail "haproxy rejected the external TLS termination config"; }
echo "HAPROXY_TLS_CONFIG_VALID=1 (real haproxy -c -f on the external terminator)"

log "starting real HAProxy TLS terminator (shared netns, plain leg over loopback)"
docker run -d --name "$HAP" --network "container:$SRV" -v "$VOL:/work:ro" \
  --entrypoint haproxy "$HAPROXY_IMAGE" -f /work/haproxy.cfg -db >/dev/null \
  || fail "start HAProxy TLS terminator"

hap_ready=0
for _ in $(seq 1 60); do
  if docker exec "$SRV" python3 -c \
      "import socket,ssl; c=ssl._create_unverified_context().wrap_socket(socket.create_connection(('127.0.0.1',${TLS_TERM_PORT}),1), server_hostname='qp'); c.close()" \
      >/dev/null 2>&1; then hap_ready=1; break; fi
  sleep 0.25
done
if [[ "$hap_ready" -ne 1 ]]; then
  docker logs "$HAP" >&2 || true
  fail "HAProxy TLS frontend never completed a handshake"
fi
